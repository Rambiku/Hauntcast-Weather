-- seed_hazards.sql
-- Populates weather_categories with the 23 canonical hazard slugs.
--
-- Schema columns used (supabase/schema.sql):
--   code          varchar(50)  UNIQUE NOT NULL  ← canonical slug
--   name          varchar(100) NOT NULL         ← English hazard name
--   description   text                          ← "group:<g> | mvp:<bool> | <human text>"
--   animation_key varchar(100)                  ← equals code; matches frontend animation folder
--
-- Language: English only. The frontend handles language switching.
-- Idempotent: skips any row whose code already exists.

